    private void actualizarImagenFuente() {
        if (cbFuente.getSelectedItem() == null) {
            return;
        }

        String seleccion = cbFuente.getSelectedItem().toString().trim();
        String rutaImagen = "";

       if (seleccion.toLowerCase().startsWith("dom")) {
         rutaImagen = "/proyecto/imagenes/domestica.png";
     } else if (seleccion.toLowerCase().startsWith("ind")) {
         rutaImagen = "/proyecto/imagenes/industria.png";
     } else if (seleccion.toLowerCase().startsWith("hosp")) {
         rutaImagen = "/proyecto/imagenes/hospital.png";
        } else {
            lblImagenFuente.setIcon(null);
            lblImagenFuente.setText("");
            return;
        }

        java.net.URL imgURL = getClass().getResource(rutaImagen);
        if (imgURL != null) {
            javax.swing.ImageIcon variable = new javax.swing.ImageIcon(imgURL);
            lblImagenFuente.setIcon(new javax.swing.ImageIcon(
                variable.getImage().getScaledInstance(
                    lblImagenFuente.getWidth(),
                    lblImagenFuente.getHeight(),
                    java.awt.Image.SCALE_DEFAULT
                )
            ));
            lblImagenFuente.setText("");
        } else {
            lblImagenFuente.setIcon(null);
            lblImagenFuente.setText("Sin imagen");
        }
    }
    
